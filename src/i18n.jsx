export function LanguageProvider({ children }) {
  // Get initial lang from localStorage or browser default, fallback to 'pt'
  const [lang, setLang] = useState(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('sebastian_lang')
      if (saved && (saved === 'pt' || saved === 'en' || saved === 'es')) return saved
    }
    return 'pt'
  })

  useEffect(() => {
    localStorage.setItem('sebastian_lang', lang)
  }, [lang])

  const t = (key) => {
    return T[lang][key] || T['pt'][key] || key
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }
  return context
}

export function LanguageSwitcher() {
  const { lang, setLang } = useLanguage()
  
  const langs = [
    { code: 'pt', label: 'PT-BR', flag: '🇧🇷' },
    { code: 'en', label: 'EN', flag: '🇺🇸' },
    { code: 'es', label: 'ES', flag: '🇪🇸' }
  ]

  return (
    <div className="flex items-center gap-1.5 border border-gold/15 bg-[#141414]/80 px-2 py-1 rounded-full backdrop-blur-sm shadow-[0_5px_15px_rgba(0,0,0,0.3)]">
      {langs.map((l) => (
        <button
          key={l.code}
          onClick={() => setLang(l.code)}
          className={`px-2.5 py-1 text-[10px] md:text-xs font-semibold tracking-wider rounded-full transition-all duration-300 ${
            lang === l.code
              ? 'bg-gradient-to-r from-gold to-gold-light text-[#0D0D0D] shadow-[0_2px_8px_rgba(201,169,110,0.4)]'
              : 'text-white/60 hover:text-gold hover:bg-white/5'
          }`}
          title={l.label}
        >
          {l.label}
        </button>
      ))}
    </div>
  )
}
